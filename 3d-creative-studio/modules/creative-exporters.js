/* ============================================================================
   3D CREATIVE STUDIO v2.0 — MODULE 4: LIVE CODE INSPECTOR & PRO EXPORTERS ($10/mo)
   Ideas #2 (Live HTML/CSS/JS Inspector Tabs) + #3 (React JSX, Vue 3 SFC,
   Web Component <script>, and Split File Package Exporter)
   ============================================================================ */
(function () {
  'use strict';

  let activeInspectorTab = 'preview'; // 'preview' | 'html' | 'css' | 'js'
  let activeFwTab = 'react';          // 'react' | 'vue' | 'webcomp' | 'split'

  function requirePro() {
    if (typeof window.isUserPremium === 'function' && !window.isUserPremium()) {
      if (typeof window.showPaywallModal === 'function') window.showPaywallModal();
      return false;
    }
    return true;
  }

  function updateInspectorView(parts) {
    const core = window.__CreativeStudioCore;
    const p = parts || core?.compileParts(false);
    if (!p) return;

    const previewBody = document.querySelector('.preview-body');
    const codeView = document.getElementById('code-inspector-wrap');
    const codeArea = document.getElementById('code-inspector-pre');
    const lineStats = document.getElementById('code-inspector-stats');

    if (activeInspectorTab === 'preview') {
      if (previewBody) previewBody.style.display = 'flex';
      if (codeView) codeView.style.display = 'none';
      return;
    }

    if (previewBody) previewBody.style.display = 'none';
    if (codeView) codeView.style.display = 'flex';

    let content = p.html;
    if (activeInspectorTab === 'css') content = p.fullCss;
    if (activeInspectorTab === 'js') content = p.fullJs || '// Pure CSS 3D component (Zero JS required)';

    if (codeArea) codeArea.textContent = content;
    if (lineStats) {
      const lines = content.split('\n').length;
      lineStats.textContent = `${activeInspectorTab.toUpperCase()} • ${lines} lines • ${content.length} chars`;
    }
  }

  function toPascalCase(str) {
    return String(str || 'CreativeWidget')
      .replace(/[^a-zA-Z0-9]+/g, ' ')
      .trim()
      .split(/\s+/)
      .map(w => w.charAt(0).toUpperCase() + w.slice(1))
      .join('') || 'Creative3DWidget';
  }

  function buildReactJSX(parts) {
    const compName = toPascalCase(parts.key);
    const scopeCss = parts.fullCss.replace(/body\s*\{/g, '.studio-3d-host {');
    return `import React, { useEffect, useRef } from 'react';

/**
 * ${compName} — Generated by IA Code Studio (3D Creative Studio v2.0)
 */
export default function ${compName}() {
  const hostRef = useRef(null);

  useEffect(() => {
    const root = hostRef.current;
    if (!root) return;
    // Inject isolated component script on mount
    const script = document.createElement('script');
    script.textContent = ${JSON.stringify(`(function(){\n${parts.fullJs}\n})();`)};
    root.appendChild(script);
    return () => {
      if (script.parentNode) script.parentNode.removeChild(script);
    };
  }, []);

  return (
    <div ref={hostRef} className="studio-3d-host" style={{ minHeight: '420px', display: 'flex', alignItems: 'center', justifyContent: 'center', position: 'relative' }}>
      <style>{\`${scopeCss.replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\`}</style>
      <div dangerouslySetInnerHTML={{ __html: ${JSON.stringify(parts.html)} }} />
    </div>
  );
}`;
  }

  function buildVueSFC(parts) {
    const scopeCss = parts.fullCss.replace(/body\s*\{/g, '.studio-3d-host {');
    return `<template>
  <div ref="hostRef" class="studio-3d-host">
    ${parts.html.replace(/\n/g, '\n    ')}
  </div>
</template>

<script setup>
import { onMounted, ref } from 'vue';

const hostRef = ref(null);

onMounted(() => {
  ${parts.fullJs.replace(/\n/g, '\n  ')}
});
<\/script>

<style scoped>
.studio-3d-host {
  min-height: 420px;
  display: flex;
  align-items: center;
  justify-content: center;
  position: relative;
}
${scopeCss}
</style>`;
  }

  function buildWebComponent(parts) {
    const tag = 'ia-3d-' + parts.key.replace(/_/g, '-');
    return `<!-- Drop-In Custom Web Component: Use <${tag}></${tag}> anywhere -->
<script>
(function () {
  if (customElements.get('${tag}')) return;
  class CreativeAsset3D extends HTMLElement {
    connectedCallback() {
      const iframe = document.createElement('iframe');
      iframe.style.cssText = 'width:100%;min-height:420px;border:0;border-radius:16px;overflow:hidden;';
      iframe.setAttribute('sandbox', 'allow-scripts');
      iframe.srcdoc = ${JSON.stringify(parts.fullHtml)};
      this.appendChild(iframe);
    }
  }
  customElements.define('${tag}', CreativeAsset3D);
})();
<\/script>
<${tag}></${tag}>`;
  }

  function buildSplitIndexHtml(parts) {
    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>3D Creative Asset — ${parts.key}</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
${parts.html}
  <script src="script.js"><\/script>
</body>
</html>`;
  }

  function refreshFrameworkCode() {
    const core = window.__CreativeStudioCore;
    const parts = core?.compileParts(false);
    const codeBox = document.getElementById('fw-export-code');
    const hintBox = document.getElementById('fw-export-hint');
    const dlSplitBtn = document.getElementById('btn-fw-download-split');
    if (!parts || !codeBox) return;

    if (activeFwTab === 'react') {
      codeBox.value = buildReactJSX(parts);
      if (hintBox) hintBox.textContent = 'Ready-to-paste React 18+ component (.jsx / .tsx compatible).';
      if (dlSplitBtn) dlSplitBtn.style.display = 'none';
    } else if (activeFwTab === 'vue') {
      codeBox.value = buildVueSFC(parts);
      if (hintBox) hintBox.textContent = 'Vue 3 Composition API Single File Component (.vue) with scoped styling.';
      if (dlSplitBtn) dlSplitBtn.style.display = 'none';
    } else if (activeFwTab === 'webcomp') {
      codeBox.value = buildWebComponent(parts);
      if (hintBox) hintBox.textContent = 'Zero-conflict sandboxed Custom Web Component (<ia-3d-...>) for WordPress, Webflow, Shopify & Notion.';
      if (dlSplitBtn) dlSplitBtn.style.display = 'none';
    } else {
      codeBox.value = `/* === index.html === */\n${buildSplitIndexHtml(parts)}\n\n/* === style.css === */\n${parts.fullCss}\n\n/* === script.js === */\n${parts.fullJs}`;
      if (hintBox) hintBox.textContent = 'Separated project files (index.html + style.css + script.js). Download all 3 clean files in 1 click.';
      if (dlSplitBtn) dlSplitBtn.style.display = 'inline-flex';
    }
  }

  function openFrameworkModal() {
    if (!requirePro()) return;
    const modal = document.getElementById('modal-frameworks');
    if (!modal) return;
    modal.style.display = 'flex';
    refreshFrameworkCode();
  }

  function bindExportersUI() {
    const core = window.__CreativeStudioCore;
    if (!core) return;

    // 1. Live Inspector Tabs (Preview | HTML | CSS | JS)
    document.querySelectorAll('.inspector-tab-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        activeInspectorTab = btn.dataset.itab;
        document.querySelectorAll('.inspector-tab-btn').forEach(b => b.classList.toggle('active', b === btn));
        updateInspectorView();
      });
    });

    const btnCopyTab = document.getElementById('btn-inspector-copy-tab');
    if (btnCopyTab) {
      btnCopyTab.addEventListener('click', () => {
        if (!requirePro()) return;
        const txt = document.getElementById('code-inspector-pre')?.textContent || '';
        navigator.clipboard.writeText(txt).then(() => {
          core.showToast(`${activeInspectorTab.toUpperCase()} snippet copied!`, 'success');
        });
      });
    }

    // 2. Pro Multi-Framework Exporter Modal
    const btnFwOpen = document.getElementById('btn-open-frameworks');
    const modal = document.getElementById('modal-frameworks');
    const btnClose = document.getElementById('btn-fw-close');
    if (btnFwOpen) btnFwOpen.addEventListener('click', openFrameworkModal);
    if (btnClose && modal) btnClose.addEventListener('click', () => { modal.style.display = 'none'; });
    if (modal) modal.addEventListener('click', (e) => { if (e.target === modal) modal.style.display = 'none'; });

    document.querySelectorAll('.fw-tab-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        activeFwTab = btn.dataset.fwtab;
        document.querySelectorAll('.fw-tab-btn').forEach(b => b.classList.toggle('active', b === btn));
        refreshFrameworkCode();
      });
    });

    const btnFwCopy = document.getElementById('btn-fw-copy');
    if (btnFwCopy) {
      btnFwCopy.addEventListener('click', () => {
        if (!requirePro()) return;
        const val = document.getElementById('fw-export-code')?.value || '';
        navigator.clipboard.writeText(val).then(() => {
          core.showToast(`${activeFwTab.toUpperCase()} code copied!`, 'success');
        });
      });
    }

    const btnSplitDl = document.getElementById('btn-fw-download-split');
    if (btnSplitDl) {
      btnSplitDl.addEventListener('click', () => {
        if (!requirePro()) return;
        const parts = core.compileParts(false);
        if (!parts) return;
        core.safeDownloadBlob(new Blob([buildSplitIndexHtml(parts)], { type: 'text/html' }), 'index.html');
        setTimeout(() => core.safeDownloadBlob(new Blob([parts.fullCss], { type: 'text/css' }), 'style.css'), 200);
        setTimeout(() => core.safeDownloadBlob(new Blob([parts.fullJs], { type: 'text/javascript' }), 'script.js'), 400);
        core.showToast('Downloaded index.html + style.css + script.js!', 'success');
      });
    }
  }

  const prevUpd = window.__CreativeStudioHooks.onPreviewUpdated;
  window.__CreativeStudioHooks.onPreviewUpdated = function (parts) {
    if (typeof prevUpd === 'function') prevUpd(parts);
    updateInspectorView(parts);
  };

  const prevReady = window.__CreativeStudioHooks.onReady;
  window.__CreativeStudioHooks.onReady = function () {
    if (typeof prevReady === 'function') prevReady();
    bindExportersUI();
    updateInspectorView();
  };

  window.__CreativeExportersV2 = {
    openFrameworkModal,
    switchInspectorTab: (tab) => {
      activeInspectorTab = tab;
      document.querySelectorAll('.inspector-tab-btn').forEach(b => b.classList.toggle('active', b.dataset.itab === tab));
      updateInspectorView();
    }
  };
})();
