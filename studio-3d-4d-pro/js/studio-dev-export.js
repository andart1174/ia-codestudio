/**
 * Studio 3D/4D Pro v2.0 — Developer Framework Exporter
 * Generates clean, production-ready React Three Fiber (.tsx), Modern Three.js ESM (.js), and <ia-3d-viewer> Web Component!
 */
(function () {
  'use strict';

  let drawer = null;
  let activeFmt = 'r3f'; // 'r3f' | 'esm' | 'wc'

  function isFR() { return (window.currentLang || 'en') === 'fr'; }

  function requirePro() {
    if (typeof window.isUserPremium === 'function' && !window.isUserPremium()) {
      if (typeof window.showPaywallModal === 'function') window.showPaywallModal();
      return false;
    }
    return true;
  }

  function collectSceneDescriptors() {
    const models = (window.SketchExtruder && window.SketchExtruder.getModels) ? window.SketchExtruder.getModels() : [];
    return models.filter(m => !m.hidden).map((m, idx) => {
      const p = m.meshGroup ? m.meshGroup.position : m.position;
      const r = m.meshGroup ? m.meshGroup.rotation : m.rotation;
      const s = m.meshGroup ? m.meshGroup.scale : m.groupScale;
      return {
        name: (m.name || ('Object' + (idx + 1))).replace(/[^a-zA-Z0-9_ ]/g, ''),
        format: m.format || m.type || 'mesh',
        color: m.colorHex || '#6366f1',
        metalness: Number((m.metalness ?? 0.5).toFixed(2)),
        roughness: Number((m.roughness ?? 0.25).toFixed(2)),
        spin: !!m.spin,
        levitate: !!m.levitate,
        pos: [Number((p.x / 20).toFixed(2)), Number((p.y / 20).toFixed(2)), Number((p.z / 20).toFixed(2))],
        rot: [Number(r.x.toFixed(2)), Number(r.y.toFixed(2)), Number(r.z.toFixed(2))],
        scl: [Number(s.x.toFixed(2)), Number(s.y.toFixed(2)), Number(s.z.toFixed(2))]
      };
    });
  }

  function buildR3FCode(items) {
    const list = items.length ? items : [{ name: 'HoloPrism', color: '#6366f1', metalness: 0.8, roughness: 0.15, spin: true, levitate: true, pos: [0,0,0], rot: [0,0,0], scl: [1,1,1] }];
    const meshes = list.map((it, i) => `      <Float speed={${it.levitate ? 2 : 0}} floatIntensity={${it.levitate ? 0.8 : 0}}>
        <mesh
          name="${it.name}"
          position={[${it.pos.join(', ')}]}
          rotation={[${it.rot.join(', ')}]}
          scale={[${it.scl.join(', ')}]}
          castShadow
          receiveShadow
        >
          ${i % 2 === 0 ? '<icosahedronGeometry args={[1.4, 0]} />' : '<torusKnotGeometry args={[1.1, 0.32, 128, 16]} />'}
          <meshStandardMaterial color="${it.color}" metalness={${it.metalness}} roughness={${it.roughness}} />
        </mesh>
      </Float>`).join('\n');

    return `// Generated by Studio 3D/4D Pro v2.0 (IA Code Studio)
// npm install three @react-three/fiber @react-three/drei
import React, { useRef } from 'react';
import { Canvas, useFrame } from '@react-three/fiber';
import { OrbitControls, Environment, Float, ContactShadows } from '@react-three/drei';
import * as THREE from 'three';

function StudioSceneGroup() {
  const groupRef = useRef<THREE.Group>(null);
  useFrame((_, delta) => {
    if (groupRef.current) groupRef.current.rotation.y += delta * 0.35;
  });

  return (
    <group ref={groupRef}>
${meshes}
    </group>
  );
}

export default function Studio3DScene() {
  return (
    <div style={{ width: '100%', height: '520px', background: '#050815', borderRadius: 16, overflow: 'hidden' }}>
      <Canvas shadows camera={{ position: [0, 2.5, 8], fov: 48 }} gl={{ toneMapping: THREE.ACESFilmicToneMapping }}>
        <color attach="background" args={['#050815']} />
        <ambientLight intensity={0.45} />
        <directionalLight position={[6, 10, 8]} intensity={1.4} castShadow />
        <Environment preset="city" />
        <StudioSceneGroup />
        <ContactShadows position={[0, -2.2, 0]} opacity={0.45} blur={2.4} />
        <OrbitControls makeDefault enableDamping />
      </Canvas>
    </div>
  );
}`;
  }

  function buildESMCode(items) {
    return `// Generated by Studio 3D/4D Pro v2.0 — Modern Three.js ES Module
// npm install three
import * as THREE from 'three';
import { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';

export function mountStudio3D(container) {
  const scene = new THREE.Scene();
  scene.background = new THREE.Color('#050815');

  const camera = new THREE.PerspectiveCamera(50, container.clientWidth / container.clientHeight, 0.1, 2000);
  camera.position.set(0, 3, 9);

  const renderer = new THREE.WebGLRenderer({ antialias: true });
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
  renderer.setSize(container.clientWidth, container.clientHeight);
  renderer.toneMapping = THREE.ACESFilmicToneMapping;
  renderer.outputColorSpace = THREE.SRGBColorSpace;
  container.appendChild(renderer.domElement);

  const controls = new OrbitControls(camera, renderer.domElement);
  controls.enableDamping = true;

  scene.add(new THREE.AmbientLight(0xffffff, 0.5));
  const dir = new THREE.DirectionalLight(0xffffff, 1.4);
  dir.position.set(6, 12, 10);
  scene.add(dir);

  const items = ${JSON.stringify(items, null, 2)};
  const group = new THREE.Group();
  items.forEach((it, idx) => {
    const geo = idx % 2 === 0 ? new THREE.IcosahedronGeometry(1.3, 0) : new THREE.TorusGeometry(1.6, 0.28, 16, 64);
    const mat = new THREE.MeshStandardMaterial({ color: it.color, metalness: it.metalness, roughness: it.roughness });
    const mesh = new THREE.Mesh(geo, mat);
    mesh.position.set(...it.pos);
    mesh.rotation.set(...it.rot);
    mesh.scale.set(...it.scl);
    group.add(mesh);
  });
  scene.add(group);

  let rafId = 0;
  const animate = () => {
    rafId = requestAnimationFrame(animate);
    group.rotation.y += 0.006;
    controls.update();
    renderer.render(scene, camera);
  };
  animate();

  const ro = new ResizeObserver(() => {
    camera.aspect = container.clientWidth / container.clientHeight;
    camera.updateProjectionMatrix();
    renderer.setSize(container.clientWidth, container.clientHeight);
  });
  ro.observe(container);

  return () => {
    cancelAnimationFrame(rafId);
    ro.disconnect();
    renderer.dispose();
    renderer.domElement.remove();
  };
}`;
  }

  function buildWebComponentCode(items) {
    return `<!-- Drop-in <ia-3d-viewer> Web Component (Zero Framework Dependencies) -->
<ia-3d-viewer style="display:block;width:100%;height:460px;border-radius:14px;overflow:hidden;"></ia-3d-viewer>
<script type="module">
import * as THREE from 'https://unpkg.com/three@0.160.0/build/three.module.js';

class IA3DViewer extends HTMLElement {
  connectedCallback() {
    const w = this.clientWidth || 640, h = this.clientHeight || 460;
    const scene = new THREE.Scene();
    scene.background = new THREE.Color('#050815');
    const camera = new THREE.PerspectiveCamera(50, w / h, 0.1, 1000);
    camera.position.set(0, 2.5, 8);
    const renderer = new THREE.WebGLRenderer({ antialias: true });
    renderer.setSize(w, h);
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    this.appendChild(renderer.domElement);
    scene.add(new THREE.AmbientLight(0xffffff, 0.6));
    const dl = new THREE.DirectionalLight(0xffffff, 1.5); dl.position.set(5, 10, 8); scene.add(dl);
    const data = ${JSON.stringify(items)};
    const grp = new THREE.Group();
    (data.length ? data : [{ color: '#6366f1', metalness: 0.8, roughness: 0.2, pos: [0,0,0] }]).forEach((it, i) => {
      const m = new THREE.Mesh(
        i % 2 === 0 ? new THREE.IcosahedronGeometry(1.4, 0) : new THREE.TorusGeometry(2.1, 0.12, 12, 64),
        new THREE.MeshStandardMaterial({ color: it.color, metalness: it.metalness, roughness: it.roughness })
      );
      m.position.set(...(it.pos || [0,0,0]));
      grp.add(m);
    });
    scene.add(grp);
    const loop = () => { this._raf = requestAnimationFrame(loop); grp.rotation.y += 0.008; renderer.render(scene, camera); };
    loop();
  }
  disconnectedCallback() { cancelAnimationFrame(this._raf); }
}
customElements.define('ia-3d-viewer', IA3DViewer);
<\/script>`;
  }

  function getCurrentCode() {
    const items = collectSceneDescriptors();
    if (activeFmt === 'r3f') return { code: buildR3FCode(items), ext: 'Studio3DScene.tsx' };
    if (activeFmt === 'esm') return { code: buildESMCode(items), ext: 'studio-3d-scene.js' };
    return { code: buildWebComponentCode(items), ext: 'ia-3d-viewer.html' };
  }

  function renderDrawer() {
    if (!drawer) return;
    const fr = isFR();
    const { code, ext } = getCurrentCode();
    drawer.panel.innerHTML = `
      ${drawer.renderHeader('💻', fr ? 'Export Développeur (React / ESM)' : 'Developer Framework Exporter')}
      <div style="display:grid;grid-template-columns:1fr 1fr 1fr;gap:5px;margin-bottom:10px;">
        <button class="studio-btn-sec dev-fmt" data-f="r3f" style="border-color:${activeFmt==='r3f'?'#22d3ee':'#334155'};background:${activeFmt==='r3f'?'rgba(34,211,238,0.2)':'#1e293b'};">⚛️ React R3F</button>
        <button class="studio-btn-sec dev-fmt" data-f="esm" style="border-color:${activeFmt==='esm'?'#22d3ee':'#334155'};background:${activeFmt==='esm'?'rgba(34,211,238,0.2)':'#1e293b'};">📦 Three ESM</button>
        <button class="studio-btn-sec dev-fmt" data-f="wc" style="border-color:${activeFmt==='wc'?'#22d3ee':'#334155'};background:${activeFmt==='wc'?'rgba(34,211,238,0.2)':'#1e293b'};">🌐 Web Comp</button>
      </div>
      <pre id="dev-code-pre" style="margin:0 0 10px;padding:10px;background:#020617;border:1px solid #1e293b;border-radius:8px;max-height:240px;overflow:auto;font-family:'JetBrains Mono',monospace;font-size:10px;line-height:1.45;color:#a5f3fc;white-space:pre;">${code.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</pre>
      <div style="display:grid;grid-template-columns:1fr 1fr;gap:6px;">
        <button id="btn-dev-copy" class="studio-btn-sec">📋 ${fr ? 'Copier Code 👑' : 'Copy Code 👑'}</button>
        <button id="btn-dev-dl" class="studio-btn-primary" style="background:linear-gradient(135deg,#06b6d4,#6366f1);">⬇️ ${ext} 👑</button>
      </div>
    `;

    drawer.panel.querySelectorAll('.dev-fmt').forEach(b => {
      b.onclick = () => { activeFmt = b.dataset.f; renderDrawer(); };
    });
    drawer.panel.querySelector('#btn-dev-copy').onclick = () => {
      if (!requirePro()) return;
      navigator.clipboard.writeText(code).then(() => {
        if (window.toast) window.toast(`✅ ${ext} copied!`);
      });
    };
    drawer.panel.querySelector('#btn-dev-dl').onclick = () => {
      if (!requirePro()) return;
      const blob = new Blob([code], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url; a.download = ext; a.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
      if (window.toast) window.toast(`✅ Downloaded ${ext}!`);
    };
  }

  window.addEventListener('studio:scenechange', () => { if (drawer && drawer.panel.classList.contains('open')) renderDrawer(); });
  window.addEventListener('studio:langchange', () => { if (drawer && drawer.panel.classList.contains('open')) renderDrawer(); });

  window.StudioDevExport = {
    toggle() {
      if (!drawer && window.StudioShellUI) drawer = window.StudioShellUI.createToolDrawer('studio-dev-export-drawer');
      if (!drawer) return;
      drawer.toggle();
      if (drawer.panel.classList.contains('open')) renderDrawer();
    }
  };
})();
