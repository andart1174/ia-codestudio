function gl() { return window.lang || 'en'; }
function t(k) { return t_db[gl()][k] || k; }

var TYPES = ['String', 'Integer', 'Float', 'Boolean', 'Date', 'UUID', 'Text', 'JSON'];

// Default schema
var schema = [
  { name: 'Users', fields: [{ name: 'id', type: 'UUID' }, { name: 'email', type: 'String' }, { name: 'password', type: 'String' }, { name: 'createdAt', type: 'Date' }] },
  { name: 'Products', fields: [{ name: 'id', type: 'UUID' }, { name: 'title', type: 'String' }, { name: 'price', type: 'Float' }, { name: 'inStock', type: 'Boolean' }] }
];

var generatedCode = '';

function generateBackendCode() {
  var isFr = gl() === 'fr';
  var lines = [];
  lines.push('<!-- ' + (isFr ? 'Backend généré par DB Architect — IA Architecte' : 'Backend generated by DB Architect — IA Architecte') + ' -->');
  lines.push('<script>');
  lines.push('// ====================================');
  lines.push('// ' + (isFr ? 'Schéma de base de données Mock' : 'Mock Database Schema'));
  lines.push('// ' + (isFr ? 'Généré automatiquement' : 'Auto-generated') + ' — ' + new Date().toLocaleDateString());
  lines.push('// ====================================');
  lines.push('');
  lines.push('const DB = {');

  schema.forEach(function(table, ti) {
    var tName = table.name.toLowerCase();
    var sampleRow = {};
    table.fields.forEach(function(f) {
      if (f.type === 'UUID') sampleRow[f.name] = 'uuid-00' + (ti + 1);
      else if (f.type === 'String') sampleRow[f.name] = 'sample_' + f.name;
      else if (f.type === 'Integer') sampleRow[f.name] = Math.floor(Math.random() * 100);
      else if (f.type === 'Float') sampleRow[f.name] = (Math.random() * 100).toFixed(2);
      else if (f.type === 'Boolean') sampleRow[f.name] = true;
      else if (f.type === 'Date') sampleRow[f.name] = new Date().toISOString();
      else if (f.type === 'Text') sampleRow[f.name] = 'Lorem ipsum...';
      else if (f.type === 'JSON') sampleRow[f.name] = '{}';
      else sampleRow[f.name] = null;
    });
    lines.push('  ' + tName + ': JSON.parse(localStorage.getItem("db_' + tName + '") || \'' + JSON.stringify([sampleRow]) + '\'),');
  });

  lines.push('};');
  lines.push('');

  schema.forEach(function(table) {
    var tName = table.name.toLowerCase();
    var TName = table.name;
    lines.push('// --- ' + TName + ' API ---');
    lines.push('const get' + TName + ' = () => DB.' + tName + ';');
    lines.push('const add' + TName + ' = (item) => { item.id = "uuid-" + Date.now(); DB.' + tName + '.push(item); localStorage.setItem("db_' + tName + '", JSON.stringify(DB.' + tName + ')); return item; };');
    lines.push('const delete' + TName + ' = (id) => { DB.' + tName + ' = DB.' + tName + '.filter(r => r.id !== id); localStorage.setItem("db_' + tName + '", JSON.stringify(DB.' + tName + ')); };');
    lines.push('const update' + TName + ' = (id, data) => { const i = DB.' + tName + '.findIndex(r => r.id === id); if(i>-1) DB.' + tName + '[i] = {...DB.' + tName + '[i], ...data}; localStorage.setItem("db_' + tName + '", JSON.stringify(DB.' + tName + ')); };');
    lines.push('');
  });

  lines.push('console.log("[DB Architect] Mock DB initialized:", DB);');
  lines.push('</script>');
  return lines.join('\n');
}

function renderDBTab() {
  var parent = document.getElementById('left-body');
  if(!parent) return;
  parent.innerHTML = '';
  var wrap = document.createElement('div');
  wrap.style = 'display:flex;flex-direction:column;height:100%;overflow:hidden;background:#0f172a;';

  var hdr = document.createElement('div');
  hdr.style = 'padding:12px 14px 8px;border-bottom:1px solid rgba(139,92,246,0.25);flex-shrink:0;display:flex;align-items:center;justify-content:space-between;';
  hdr.innerHTML = '<div><div style="font-size:13px;font-weight:900;color:#a78bfa;">' + t('title') + '</div><div style="font-size:10px;color:#94a3b8;margin-top:2px;">' + t('sub') + '</div></div>';

  var addBtn = document.createElement('button');
  addBtn.textContent = t('addTable');
  addBtn.style = 'background:#8b5cf6;color:#fff;border:none;padding:6px 10px;border-radius:6px;font-size:10px;font-weight:bold;cursor:pointer;white-space:nowrap;';
  addBtn.onclick = function() {
    var name = prompt(t('placeholder'));
    if (!name) return;
    schema.push({ name: name.trim(), fields: [{ name: 'id', type: 'UUID' }] });
    renderDBTab();
  };
  hdr.appendChild(addBtn);
  wrap.appendChild(hdr);

  var body = document.createElement('div');
  body.style = 'flex:1;overflow-y:auto;padding:12px;display:flex;flex-direction:column;gap:12px;';

  schema.forEach(function(table, ti) {
    var card = document.createElement('div');
    card.style = 'background:#1e293b;border:1px solid #334155;border-radius:10px;overflow:hidden;';

    var cardHead = document.createElement('div');
    cardHead.style = 'background:#334155;padding:8px 12px;font-size:11px;font-weight:bold;color:#e2e8f0;display:flex;justify-content:space-between;align-items:center;';
    cardHead.innerHTML = '<span>📄 ' + table.name + '</span>';

    var delTbl = document.createElement('button');
    delTbl.textContent = '🗑️';
    delTbl.style = 'background:none;border:none;cursor:pointer;font-size:13px;';
    delTbl.onclick = function() {
      if (confirm(t('confirmDel'))) { schema.splice(ti, 1); renderDBTab(); }
    };
    cardHead.appendChild(delTbl);
    card.appendChild(cardHead);

    var fieldList = document.createElement('div');
    fieldList.style = 'padding:8px;display:flex;flex-direction:column;gap:4px;';

    table.fields.forEach(function(field, fi) {
      var row = document.createElement('div');
      row.style = 'display:flex;align-items:center;gap:6px;';

      var nameInp = document.createElement('input');
      nameInp.value = field.name;
      nameInp.style = 'flex:1;background:#0f172a;color:#e2e8f0;border:1px solid #475569;padding:4px 6px;border-radius:4px;font-size:10px;';
      nameInp.onchange = function() { field.name = this.value; };

      var typeSelect = document.createElement('select');
      typeSelect.style = 'background:#0f172a;color:#94a3b8;border:1px solid #475569;padding:4px;border-radius:4px;font-size:10px;';
      TYPES.forEach(function(tp) {
        var opt = document.createElement('option');
        opt.value = tp; opt.textContent = tp;
        if (tp === field.type) opt.selected = true;
        typeSelect.appendChild(opt);
      });
      typeSelect.onchange = function() { field.type = this.value; };

      var delField = document.createElement('button');
      delField.textContent = t('delField');
      delField.style = 'background:none;border:none;color:#ef4444;cursor:pointer;font-size:11px;font-weight:bold;';
      delField.onclick = function() { table.fields.splice(fi, 1); renderDBTab(); };

      row.appendChild(nameInp); row.appendChild(typeSelect); row.appendChild(delField);
      fieldList.appendChild(row);
    });

    var addFieldBtn = document.createElement('button');
    addFieldBtn.textContent = t('addField');
    addFieldBtn.style = 'width:100%;background:none;border:1px dashed #475569;color:#64748b;padding:5px;border-radius:6px;font-size:10px;cursor:pointer;margin-top:4px;';
    addFieldBtn.onclick = function() {
      var fn = prompt(t('fieldName'));
      if (!fn) return;
      table.fields.push({ name: fn.trim(), type: 'String' });
      renderDBTab();
    };
    fieldList.appendChild(addFieldBtn);
    card.appendChild(fieldList);
    body.appendChild(card);
  });

  var genBtn = document.createElement('button');
  genBtn.innerHTML = t('gen');
  genBtn.style = 'width:100%;background:linear-gradient(90deg,#8b5cf6,#6d28d9);color:#fff;border:none;padding:12px;border-radius:8px;font-weight:900;cursor:pointer;';
  genBtn.onclick = function() {
    generatedCode = generateBackendCode();
    showCodeResult(body, generatedCode);
  };
  body.appendChild(genBtn);

  if (generatedCode) {
    showCodeResult(body, generatedCode);
  }

  wrap.appendChild(body);
  parent.appendChild(wrap);
}

function showCodeResult(body, code) {
  var old = document.getElementById('db-result-zone');
  if (old) old.remove();
  var zone = document.createElement('div');
  zone.id = 'db-result-zone';
  zone.style = 'display:flex;flex-direction:column;gap:8px;';

  var pre = document.createElement('pre');
  pre.style = 'background:#000;color:#94a3b8;padding:10px;border-radius:8px;font-size:9px;overflow-x:auto;white-space:pre-wrap;border:1px solid #334155;max-height:200px;';
  pre.textContent = code;
  zone.appendChild(pre);

  var btnRow = document.createElement('div');
  btnRow.style = 'display:flex;gap:8px;';

  var btnCopy = document.createElement('button');
  btnCopy.textContent = t('copy');
  btnCopy.style = 'flex:1;background:#334155;color:#e2e8f0;border:none;padding:8px;border-radius:6px;font-size:11px;cursor:pointer;';
  btnCopy.onclick = function() {
    navigator.clipboard.writeText(code);
    btnCopy.textContent = t('copied');
    setTimeout(function() { btnCopy.textContent = t('copy'); }, 2000);
  };

  var btnInj = document.createElement('button');
  btnInj.textContent = t('inject');
  btnInj.style = 'flex:1;background:#8b5cf6;color:#fff;border:none;padding:8px;border-radius:6px;font-size:11px;cursor:pointer;';
  btnInj.onclick = function() {
    if (!window.editor) return;
    var edCode = window.editor.getValue();
    if (edCode.includes('</head>')) {
      window.editor.setValue(edCode.replace('</head>', code + '\n</head>'));
    } else {
      window.editor.setValue(code + '\n' + edCode);
    }
    if (window.runPreview) window.runPreview();
    if (window.showToast) window.showToast(gl()==='fr'?'Backend injecté!':'Backend injected!');
  };

  btnRow.appendChild(btnCopy); btnRow.appendChild(btnInj);
  zone.appendChild(btnRow);
  body.appendChild(zone);
}

