window.I18N = {
    currentLang: localStorage.getItem('creative_studio_lang') || 'en',
    
    setLang(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('creative_studio_lang', lang);
            this.applyTranslations();
        }
    },
    
    t(key) {
        return (translations[this.currentLang] && translations[this.currentLang][key]) || key;
    },
    
    applyTranslations() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (this.t(key)) el.textContent = this.t(key);
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (this.t(key)) el.setAttribute('placeholder', this.t(key));
        });

        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === this.currentLang);
        });
    }
};
