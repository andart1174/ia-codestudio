let currentLang = 'en';

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'fr') lang = 'en';
  currentLang = lang;
  localStorage.setItem('studio_lang', lang);
  
  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (studioTranslations[lang] && studioTranslations[lang][key]) {
      el.textContent = studioTranslations[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (studioTranslations[lang] && studioTranslations[lang][key]) {
      el.setAttribute('placeholder', studioTranslations[lang][key]);
    }
  });

  // Update optgroup labels
  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-label');
    if (studioTranslations[lang] && studioTranslations[lang][key]) {
      el.setAttribute('label', studioTranslations[lang][key]);
    }
  });

  // Update active state of language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  document.documentElement.lang = lang;
}

function initLanguage() {
  const saved = localStorage.getItem('studio_lang');
  if (saved === 'fr' || saved === 'en') {
    setLanguage(saved);
    return;
  }
  const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (browserLang.startsWith('fr')) {
    setLanguage('fr');
  } else {
    setLanguage('en');
  }
}
